/**
 * Expo config plugin: point the app's Android backup rules at Cleanway's own
 * files, which keep the block log and the "not a scam" list on the phone.
 *
 * Why: BlockLog (SharedPreferences "cleanway_block_log") is every site the
 * shield or link guard stopped or warned about, with times — a browsing trail.
 * UserAllow ("cleanway_user_allow") is the person's own allow list. Android
 * Auto Backup copied both to Google Drive and to a new phone, because the only
 * rules in the app were expo-secure-store's, which exclude SecureStore alone.
 *
 * The rule files live in the native module's resources
 * (modules/cleanway-vpn/android/src/main/res/xml/) and merge into the app, so
 * this plugin only sets the two <application> attributes. expo-secure-store's
 * own backup plugin is turned off in app.json (configureAndroidBackup: false);
 * our files carry its SecureStore exclusion too. The AndroidManifest is
 * regenerated by every `expo prebuild`, hence a plugin.
 */
const { withAndroidManifest, AndroidConfig } = require("@expo/config-plugins");

const FULL_BACKUP_CONTENT = "@xml/cleanway_backup_rules"; // Android 11 and lower
const DATA_EXTRACTION_RULES = "@xml/cleanway_data_extraction_rules"; // Android 12+

function apply(manifest) {
  const app = AndroidConfig.Manifest.getMainApplicationOrThrow(manifest);
  app.$["android:fullBackupContent"] = FULL_BACKUP_CONTENT;
  app.$["android:dataExtractionRules"] = DATA_EXTRACTION_RULES;
  return manifest;
}

module.exports = function withBackupRules(config) {
  return withAndroidManifest(config, (cfg) => {
    cfg.modResults = apply(cfg.modResults);
    return cfg;
  });
};

module.exports._apply = apply;
module.exports.FULL_BACKUP_CONTENT = FULL_BACKUP_CONTENT;
module.exports.DATA_EXTRACTION_RULES = DATA_EXTRACTION_RULES;

/**
 * Expo config plugin: declare the portrait-screen feature as not required.
 *
 * Why: `"orientation": "portrait"` in app.json puts
 * android:screenOrientation="portrait" on the activity, and Android then
 * assumes `<uses-feature android:name="android.hardware.screen.portrait">` is
 * REQUIRED. Google Play hides the app from devices that do not report that
 * feature (some tablets, Chromebooks, Android XR) and warned about it at the
 * pre-review check of 1.1.0 (111), 2026-11-18. The app still runs in portrait;
 * the explicit required="false" only stops Play from filtering devices.
 * The AndroidManifest is regenerated by every `expo prebuild`, hence a plugin.
 */
const { withAndroidManifest } = require("@expo/config-plugins");

const FEATURE = "android.hardware.screen.portrait";

function apply(manifest) {
  const m = manifest.manifest;
  const list = (m["uses-feature"] = m["uses-feature"] || []);
  const found = list.find((f) => f.$ && f.$["android:name"] === FEATURE);
  if (found) found.$["android:required"] = "false";
  else list.push({ $: { "android:name": FEATURE, "android:required": "false" } });
  return manifest;
}

module.exports = function withPortraitOptional(config) {
  return withAndroidManifest(config, (cfg) => {
    cfg.modResults = apply(cfg.modResults);
    return cfg;
  });
};

module.exports._apply = apply;
module.exports.FEATURE = FEATURE;

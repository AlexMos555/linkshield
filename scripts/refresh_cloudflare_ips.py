#!/usr/bin/env python3
"""Refresh api/data/cloudflare_ips.txt from Cloudflare's published ranges.

The API believes CF-Connecting-IP only when the hop in front of Railway's edge
is inside these ranges (api/services/proxy_trust.py). Cloudflare changes the
list rarely and announces it; refresh before turning the proxy on and when
Cloudflare announces a change, then commit the diff.

Usage:
    python scripts/refresh_cloudflare_ips.py            # rewrite the file
    python scripts/refresh_cloudflare_ips.py --check    # exit 1 if stale
"""
from __future__ import annotations

import argparse
import datetime
import ipaddress
import pathlib
import sys

SOURCES = {4: "https://www.cloudflare.com/ips-v4", 6: "https://www.cloudflare.com/ips-v6"}
OUT = pathlib.Path(__file__).resolve().parent.parent / "api" / "data" / "cloudflare_ips.txt"


def parse_ranges(text: str, version: int) -> list[ipaddress._BaseNetwork]:
    """Every line a public CIDR of the expected family, or ValueError —
    a captive portal, an error page or an empty body never reaches the file."""
    nets = []
    for line in text.splitlines():
        line = line.strip()
        if not line:
            continue
        net = ipaddress.ip_network(line, strict=True)
        if net.version != version:
            raise ValueError(f"IPv{net.version} range in the IPv{version} list: {line}")
        if not net.is_global:
            raise ValueError(f"non-public range: {line}")
        nets.append(net)
    if not nets:
        raise ValueError(f"empty IPv{version} list")
    return nets


def render(v4, v6) -> str:
    today = datetime.date.today().isoformat()
    header = (
        "# Cloudflare edge ranges (https://www.cloudflare.com/ips/).\n"
        f"# Generated by scripts/refresh_cloudflare_ips.py on {today}. Do not edit by hand.\n"
    )
    return header + "".join(f"{n}\n" for n in [*v4, *v6])


def fetch() -> str:
    import httpx

    parts = {}
    for version, url in SOURCES.items():
        resp = httpx.get(url, timeout=20, follow_redirects=True)
        resp.raise_for_status()
        parts[version] = parse_ranges(resp.text, version)
    return render(parts[4], parts[6])


def _ranges_only(text: str) -> list[str]:
    return [line for line in text.splitlines() if line and not line.startswith("#")]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 when the vendored file is stale")
    args = ap.parse_args()
    fresh = fetch()
    current = OUT.read_text() if OUT.exists() else ""
    if _ranges_only(fresh) == _ranges_only(current):
        print("cloudflare_ips.txt is up to date")
        return 0
    if args.check:
        print("cloudflare_ips.txt is stale — run scripts/refresh_cloudflare_ips.py", file=sys.stderr)
        return 1
    OUT.write_text(fresh)
    print(f"wrote {OUT} ({len(_ranges_only(fresh))} ranges)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
